#!/usr/bin/env python3
"""Export website glossary text from the game's shipped Brazilian catalogue.

Run with --game-root /path/to/JiuJitsuRPG/jiu-jitsu-rpg, optionally --check.
The game's existing parsers own both source formats; this exports only text,
leaving all gameplay values in the existing generated glossary.json.
"""
from __future__ import annotations

import argparse
import importlib
import json
import re
import sys
from pathlib import Path

SITE_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = SITE_ROOT / "src/lib/i18n/glossary-game.pt-BR.json"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--game-root", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    game = args.game_root.resolve()
    sys.path.insert(0, str(game / "tools"))
    exporter = importlib.import_module("export_glossary")
    locales = importlib.import_module("loc_core")
    catalogue = locales.parse_po(game / "locales/pt_BR.po")
    source, _ = exporter.build()
    read_source = exporter._read
    used: dict[str, str] = {}
    missing: set[str] = set()
    pair = re.compile(r'"(?P<field>\w+)_key":\s*"(?P<key>[^"\n]+)",\s*"(?P=field)_en":\s*"(?P<english>(?:[^"\\]|\\.)*)"')

    def localize(match: re.Match[str]) -> str:
        key = match["key"]
        translated = catalogue.get(key)
        if not translated:
            missing.add(key)
            return match[0]
        # Keep the game wording; normalize the one legacy punctuation mark.
        translated = translated.replace(" \u2014 ", ": ")
        used[key] = translated
        prefix = match[0][:match[0].rfind('"' + match["field"] + '_en"')]
        return prefix + '"' + match["field"] + '_en": ' + json.dumps(translated, ensure_ascii=False)

    def localized_read(path: Path) -> str:
        return pair.sub(localize, read_source(path))

    exporter._read = localized_read
    translated, _ = exporter.build()
    exporter._read = read_source
    original_moves = {move["id"]: move for move in source["moves"]}
    translated_moves = {move["id"]: move for move in translated["moves"]}
    if set(original_moves) != set(translated_moves):
        raise RuntimeError("Localization changed move identities")

    def fields(value: dict, names: tuple[str, ...]) -> dict:
        return {name: value[name] for name in names if name in value}

    positions = {position["id"]: fields(position, ("name", "description")) for position in translated["positions"]}
    moves = {mid: fields(move, ("name", "description", "shortName")) for mid, move in translated_moves.items()}
    if len(source["families"]) != len(translated["families"]):
        raise RuntimeError("Localization changed family count")
    families = {base["id"]: fields(local, ("label", "topLabel", "bottomLabel")) for base, local in zip(source["families"], translated["families"])}
    reasons: dict[str, str] = {}
    acquisitions: dict[str, str] = {}
    for mid, move in translated_moves.items():
        for rivalry in move.get("rivalries", {}).get("strongVs", []):
            reasons[f"{mid}:{rivalry['move']}"] = rivalry["reason"]
        for field in ("gym", "course", "occasion", "teacher"):
            base = original_moves[mid]["acquisition"].get(field)
            local = move["acquisition"].get(field)
            if base and local:
                acquisitions[base] = local

    # Require every displayed move and position to have both localized fields.
    required = {f"move.{mid}.{field}" for mid in moves for field in ("name", "desc")}
    required |= {f"combat.pos.{pid}.{field}" for pid in positions for field in ("name", "desc")}
    absent = sorted(key for key in required if key not in used)
    if absent:
        raise RuntimeError(f"Displayed glossary strings have no catalogue translation: {absent}")
    payload = {
        "source": "Generated by tools/export-glossary-locale.py from game pt_BR.po; do not edit by hand.",
        "positions": positions,
        "moves": moves,
        "families": families,
        "rivalries": reasons,
        "acquisition": acquisitions,
        "stats": {stat: catalogue[f"combat.stat.{stat}"] for stat in sorted({move["stat"] for move in source["moves"] if move["stat"]})},
        "rarities": {rarity: catalogue[f"ui.rarity.{rarity}"] for rarity in source["theme"]["rarityLevels"]},
        "belts": {belt: catalogue[f"combat.belt.{belt}.label"] for belt in ("white", "blue", "purple", "brown", "black")},
    }
    rendered = json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != rendered:
            print(f"STALE: {OUTPUT}", file=sys.stderr)
            return 1
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(rendered)
    print(f"OK: {len(moves)} moves, {len(positions)} positions, {len(families)} families, {len(reasons)} rivalry pairs from pt_BR.po")
    if missing:
        print(f"Note: {len(missing)} unrelated source strings have no catalogue entry; none are required move/position text.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
